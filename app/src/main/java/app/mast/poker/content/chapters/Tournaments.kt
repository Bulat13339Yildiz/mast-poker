/** Four equal stacks, three paid 50/30/20: the bubble example, computed rather than typed. */
internal object BubbleExample {
    val prizes = listOf(50.0, 30.0, 20.0)
    val before: Double = Icm.equities(List(4) { 2500.0 }, prizes)[0]
    val afterDouble: Double = Icm.equities(listOf(5000.0, 2500.0, 2500.0), prizes)[0]
    /** Win chance a call needs so that winning (afterDouble) or busting (0) beats folding (before). */
    val needToCall: Double = before / afterDouble
}

private fun pct(x: Double) = "${x.roundToInt()}%"

