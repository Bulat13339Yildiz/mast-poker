        lesson("math_decide", "Колл или фолд", "Ауты против цены", minutes = 5, unlocksDrill = DrillType.POT_ODDS) {
            theory(
                "Всё вместе",
                """
                **1.** Посчитай ауты.
                **2.** Переведи в проценты (×2 или ×4).
                **3.** Посчитай, какой шанс требует банк.
                **4.** Твой шанс больше — колл. Меньше — фолд.
                """,
            )
            theory(
                "Пример",
                """
                Тёрн, у тебя флеш-дро: 9 аутов ≈ **18%**.

                В банке 100, соперник ставит 100. Нужно 33%. 18% меньше — **фолд**.

                А если бы он поставил 20? Нужно 20 ÷ 140 ≈ 14%. 18% больше — **колл**.
                """,
            )
            theory(
                "Скрытые шансы",
                """
                Иногда колл с чуть худшими шансами всё-таки оправдан: если соберёшь руку, соперник может заплатить ещё. Это называют **скрытыми шансами**.

                Но сначала научись честной арифметике — она защитит от самых дорогих ошибок.
                """,
            )
            remember("Мой шанс больше нужного — колл. Меньше — фолд.")
            callOrFold(
                "Тёрн. У тебя флеш-дро (9 аутов). Банк вместе со ставкой — 150, колл — 50.",
                pot = 150, call = 50, outs = 9, cardsToCome = 1,
                explanation = "Шанс ≈ 9 × 2 = 18%. Нужно 50 ÷ 200 = 25%. 18% меньше 25% — фолд.",
            )
            callOrFold(
                "Тёрн. Двусторонний стрит-дро (8 аутов). Банк со ставкой — 120, колл — 20.",
