            theory(
                "Что такое аут",
                """
                **Аут** — карта, которая улучшит твою руку до, скорее всего, выигрышной.

                Пока руки нет, считай, сколько таких карт ещё осталось в колоде.
                """,
            )
            theory(
                "Флеш-дро",
                """
                У тебя четыре карты одной масти, не хватает одной. В масти 13 карт, четыре ты видишь, значит, осталось **9 аутов**.
                """,
                hand("Ah Kh", "7h 2h 9c", caption = "Любая черва даст флеш — 9 аутов"),
