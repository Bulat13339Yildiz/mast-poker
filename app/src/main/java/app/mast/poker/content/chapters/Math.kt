                """
                **Двусторонний**: 9-8 на флопе 7-6-2. Стрит дадут любая пятёрка или любая десятка: 4 + 4 = **8 аутов**.

                **Гатшот** (дыра в середине): 9-8 на флопе 6-5-K. Нужна только семёрка — **4 аута**.
                """,
                hand("9c 8d", "7h 6s 2c", caption = "Пятёрка или десятка — 8 аутов"),
            )
            theory(
                "Не считай дважды",
