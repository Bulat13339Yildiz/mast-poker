        lesson("math_rule", "Правило 2 и 4", "Проценты в уме за секунду", minutes = 4) {
            theory(
                "Быстрый подсчёт",
                """
                Умножь число аутов:

                **на 4** — если впереди две карты и ты точно их увидишь (например, на флопе кто-то пошёл олл-ин);
                **на 2** — если впереди одна карта.

                Получишь примерный шанс собрать руку в процентах.
                """,
            )
            theory(
                "Проверим",
                """
                Флеш-дро на флопе: 9 × 4 ≈ **36%** к риверу. Точно — 35%.

                Флеш-дро на тёрне: 9 × 2 ≈ **18%** на ривере. Точно — около 20%.

                Правило почти не ошибается, а считается в уме за секунду.
                """,
            )
            theory(
                "Осторожно с ×4",
                """
                ×4 работает, только если ты гарантированно увидишь обе карты. Если на тёрне соперник поставит снова, придётся платить ещё раз. Поэтому в обычной ситуации честнее считать **×2 на каждую улицу**.
                """,
            )
            remember("Ауты × 2 — шанс на следующей карте. Ауты × 4 — шанс к риверу, если увидишь обе карты.")
