            outs("Сколько аутов до стрита?", "9c 8d", "7h 6s 2c", STRAIGHT, listOf(4, 6, 8, 9), "Подойдут четыре пятёрки и четыре десятки — 8 аутов.")
            outs("А здесь? Сколько аутов до стрита?", "9c 8d", "6h 5s Kc", STRAIGHT, listOf(3, 4, 8, 9), "Стрит даст только семёрка — их в колоде четыре.")
            outs(
                "Сколько аутов до стрита или чего-то сильнее?",
                "9h 8h", "7h 6c 2h", STRAIGHT, listOf(9, 12, 15, 17),
                "9 червей дают флеш, ещё 6 пятёрок и десяток других мастей — стрит. Всего 15.",
            )
