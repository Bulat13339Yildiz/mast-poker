        lesson("math_pot", "Шансы банка", "Сколько платишь и за что", minutes = 5) {
            theory(
                "Цена колла",
                """
                Перед коллом спроси: сколько я плачу и сколько могу выиграть?

                В банке 100, соперник ставит 50. Банк стал **150**, тебе нужно доплатить **50**. После колла в банке 200, и твоя доля в нём — 50.
                """,
            )
            theory(
                "Формула",
                """
                **Нужный шанс = колл ÷ (банк + колл)**, где банк — уже со ставкой соперника.

                В примере: 50 ÷ (150 + 50) = **25%**. Если твой шанс собрать руку больше 25%, колл выгоден на дистанции.
                """,
                Visual.PotMath(pot = 150, call = 50),
            )
            theory(
                "Удобные ориентиры",
                """
                Ставка в **треть банка** → нужно 20%.
                Ставка в **полбанка** → нужно 25%.
                Ставка **в банк** → нужно 33%.

                Запомни эти три числа — так быстрее, чем считать каждый раз.
                """,
            )
            remember("Нужный шанс = колл ÷ (банк со ставкой + колл). Треть банка — 20%, половина — 25%, банк — 33%.")
            choice(
                "В банке 60 вместе со ставкой соперника, колл — 20. Какой шанс нужен?",
                "25%",
                "33%",
                "20%",
                explanation = "20 ÷ (60 + 20) = 20 ÷ 80 = 25%.",
                concept = Concept.POT_ODDS,
            )
            choice(
                "Соперник ставит размер банка. Сколько нужно шансов для колла?",
                "33%",
                "50%",
                "25%",
                explanation = "Банк P, ставка P: колл P ÷ (2P + P) = 1/3 ≈ 33%.",
